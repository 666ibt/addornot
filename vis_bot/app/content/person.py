"""Рассылка про великую личность: справка, достижения и пара цитат.

Источник по приоритету:
1) транскрипт свежего ролика с настроенных YouTube-каналов (Минаев Live и т.п.);
2) если транскрипта нет — обычный веб-поиск (статьи/материалы, без Википедии).
"""
from __future__ import annotations

import logging

from . import claude_client, youtube

logger = logging.getLogger(__name__)

_FORMAT = (
    "Составь короткую заметку для Telegram (parse_mode=HTML).\n\n"
    "Структура:\n"
    "👤 <b>Имя личности</b> (годы жизни)\n\n"
    "1–2 абзаца: кто это и чем важен.\n\n"
    "<b>Достижения:</b> 3–4 пункта списком.\n\n"
    "<b>Цитаты:</b> 2–3 цитаты курсивом (<i>...</i>).\n\n"
    "Используй только теги <b> и <i>. Без ссылок и сносок в тексте."
)

# --- Вариант 1: на основе транскрипта YouTube-ролика ---

_SYSTEM_YT = (
    "Ты — автор просветительской рубрики о выдающихся людях. Пишешь точно, "
    "увлекательно и на русском. Тебе дают транскрипт популярного русскоязычного "
    "YouTube-разбора (например, «Минаев Live»). Транскрипт — авторасшифровка и может "
    "содержать ошибки распознавания, поэтому факты и особенно цитаты критически "
    "перепроверяй веб-поиском. Википедию как источник НЕ используй. "
    "Цитаты приводи только реально принадлежащие человеку."
)


async def _from_transcript(transcript: str) -> str:
    prompt = (
        "Ниже — транскрипт YouTube-разбора. Определи центральную историческую или "
        "общественную личность, о которой идёт речь, и составь о ней заметку. "
        "Опирайся на содержание ролика, но факты и цитаты сверь веб-поиском "
        "(без Википедии).\n\n"
        f"{_FORMAT}\n\n"
        "=== ТРАНСКРИПТ РОЛИКА ===\n"
        f"{transcript}"
    )
    return await claude_client.generate(
        _SYSTEM_YT, prompt, use_web_search=True, max_tokens=3000
    )


# --- Вариант 2: только веб-поиск ---

_SYSTEM_WEB = (
    "Ты — автор просветительской рубрики о выдающихся людях всех времён: учёных, "
    "мыслителях, художниках, инженерах, общественных деятелях. Пишешь увлекательно, "
    "точно и на русском. Цитаты приводишь только реально принадлежащие человеку.\n\n"
    "Источники: интернет (статьи, материалы, очерки), книги и популярные "
    "русскоязычные YouTube-разборы (например, «Минаев Live»). "
    "Википедию как источник НЕ используй."
)

_PROMPT_WEB = (
    "Выбери одну выдающуюся историческую или современную личность, найди о ней "
    "информацию веб-поиском (статьи, материалы, разборы; без Википедии) и составь "
    "заметку.\n\n" + _FORMAT
)


async def _from_web() -> str:
    return await claude_client.generate(
        _SYSTEM_WEB, _PROMPT_WEB, use_web_search=True, max_tokens=3000
    )


async def daily_person() -> str:
    if youtube.has_channels():
        try:
            material = await youtube.daily_transcript()
            if material:
                transcript, video_id = material
                logger.info("Заметка о личности по ролику %s", video_id)
                return await _from_transcript(transcript)
            logger.info("Свежих роликов с субтитрами нет — иду в веб-поиск")
        except Exception:
            logger.exception("Сбой при получении транскрипта — откат на веб-поиск")
    return await _from_web()
