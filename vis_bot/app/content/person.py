"""Рассылка про великую личность: справка, достижения и пара цитат."""
from __future__ import annotations

from . import claude_client

_SYSTEM = (
    "Ты — автор просветительской рубрики о выдающихся людях всех времён: учёных, "
    "мыслителях, художниках, инженерах, общественных деятелях. Пишешь увлекательно, "
    "точно и на русском. Цитаты приводишь только реально принадлежащие человеку.\n\n"
    "Источники: опирайся на интернет (статьи, материалы, очерки), книги и "
    "популярные русскоязычные YouTube-разборы (например, «Минаев Live» и подобные "
    "историко-просветительские каналы). Википедию НЕ используй как источник."
)

_PROMPT = (
    "Выбери одну выдающуюся историческую или современную личность. Найди через "
    "веб-поиск информацию о ней в статьях, книжных материалах и популярных "
    "YouTube-разборах (Минаев Live и т.п.); Википедию не используй. "
    "Составь короткую заметку для Telegram (parse_mode=HTML).\n\n"
    "Структура:\n"
    "👤 <b>Имя личности</b> (годы жизни)\n\n"
    "1–2 абзаца: кто это и чем важен.\n\n"
    "<b>Достижения:</b> 3–4 пункта списком.\n\n"
    "<b>Цитаты:</b> 2–3 цитаты курсивом (<i>...</i>).\n\n"
    "Используй только теги <b> и <i>. Без ссылок и сносок в тексте."
)


async def daily_person() -> str:
    return await claude_client.generate(_SYSTEM, _PROMPT, use_web_search=True, max_tokens=3000)
