"""Ежедневные новости: только крупные события мирового масштаба."""
from __future__ import annotations

from . import claude_client

_SYSTEM = (
    "Ты — редактор краткого новостного дайджеста на русском языке. "
    "Отбираешь ТОЛЬКО действительно крупные события, которые имеют глобальное "
    "значение и влияют на мир в целом: геополитика, мировая экономика, наука и "
    "технологии, климат, крупные катастрофы. Игнорируешь локальные, развлекательные "
    "и проходные новости. Пиши нейтрально, без оценок и кликбейта.\n\n"
    "Источники: новостные сайты, статьи и материалы из интернета. "
    "Википедию как источник не используй."
)

_PROMPT = (
    "Найди через веб-поиск самые важные мировые новости за последние 24 часа и "
    "составь дайджест.\n\n"
    "Формат:\n"
    "🌍 <b>Главное за день</b>\n\n"
    "Затем 3–5 пунктов. Каждый пункт: с новой строки эмодзи-маркер, "
    "жирным заголовок (тег <b>), затем 1–2 предложения сути.\n\n"
    "Если по-настоящему глобальных новостей мало — дай меньше пунктов, не выдумывай. "
    "Используй только HTML-теги <b>, <i> (Telegram parse_mode=HTML). "
    "Никаких ссылок и сносок в тексте."
)


async def daily_news() -> str:
    return await claude_client.generate(_SYSTEM, _PROMPT, use_web_search=True, max_tokens=4000)
