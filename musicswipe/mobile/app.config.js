const base = require('./app.json').expo;

/**
 * Конфигурация приложения.
 *
 * Настройки Supabase кладутся в `extra` здесь, а не читаются из
 * `process.env` внутри приложения. Разница принципиальная:
 *
 *   - `process.env.EXPO_PUBLIC_*` подставляется в код на этапе сборки бандла,
 *     и Metro кэширует результат. Если первый запуск случился до появления
 *     `.env`, переменные останутся пустыми, сколько ни перезапускай, — лечится
 *     только `--clear`, о чём догадаться неоткуда.
 *   - `extra` приезжает в приложение вместе с манифестом, а этот файл
 *     вычисляется заново при каждом старте дев-сервера. Поправили `.env` —
 *     перезагрузили приложение, и всё на месте.
 *
 * Файл `.env` загружается Expo CLI до вычисления конфигурации, поэтому
 * `process.env` здесь уже заполнен.
 */
module.exports = () => ({
  ...base,
  extra: {
    ...base.extra,
    supabaseUrl: process.env.EXPO_PUBLIC_SUPABASE_URL ?? '',
    supabaseAnonKey: process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? '',
  },
});
